    WIN_IMU  = 100
    STEP_IMU = 50
    GYRO_THR = 50    # dps — quiet period threshold
    GYRO_PCT = 0.90  # fraction of window that must be quiet

    rows = []
    for i in range(0, len(imu_s6) - WIN_IMU, STEP_IMU):
        seg_imu = imu_s6.iloc[i:i + WIN_IMU]
        if (seg_imu['gyro_mag'] < GYRO_THR).mean() < GYRO_PCT:
            continue
